#include "libft.h"

int	ft_lstsize(t_list *lst)
{
	int	l;

	l = 0;
	if (lst == NULL)
		return (l);
	l++;
	while (lst->next)
	{
		lst = lst->next;
		l++;
	}
	return (l);
}
