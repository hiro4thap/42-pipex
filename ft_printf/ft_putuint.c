#include "ft_printf.h"

int	ft_putuint(unsigned int n)
{
	int		i;

	i = 0;
	if (0 < n / 10)
		i = ft_putuint(n / 10);
	ft_putchar((n % 10) + '0');
	i++;
	return (i);
}
